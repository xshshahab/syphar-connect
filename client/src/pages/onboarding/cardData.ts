export type Tone =
  | "pending" // amber
  | "accepted" // green
  | "rejected" // red
  | "interview" // blue
  | "meeting" // purple
  | "offer" // bright green
  | "neutral"
  | "red";

export type CardSpec = {
  side: "l" | "r"; // which edge `x` is measured from (% of the width)
  x: number;
  y: number; // % of the height
  rot: number; // degrees
  w: number; // width in em
  depth?: 0 | 1 | 2; // 0 front and sharp, 2 far, dim and blurred
  glow?: boolean; // bright red border
  icon?: LucideIcon;
  iconTone?: Tone;
  avatar?: string; // initials, instead of an icon
  label?: string; // status line above the title
  tone?: Tone; // colour of the status line
  title: string;
  sub?: string;
  left?: string; // bottom row, bold
  right?: string; // bottom row, with a pin
  bookmark?: "saved" | "empty";
  progress?: number; // 0-100
};

